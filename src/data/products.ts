// Map all real data products from catalog files into standard Product entities
const mappedOlflexProducts: Product[] = ALL_OLFLEX_PRODUCTS.map((item, idx) => {
  const isSteelBraided = item.name.includes("SY") || (item.desc && item.desc.includes("Steel"));
  const isCopperScreened = item.name.includes("CY");
  const isColorCoded = item.name.includes("100") || (item.desc && item.desc.includes("Colour"));

  let image = "/images/cable-olflex-thumb.png";
  if (isSteelBraided) image = "/images/card-olflex.jpg";
  else if (isCopperScreened) image = "/images/card-unitronic.jpg";
  else if (isColorCoded) image = "/images/card-cables.jpg";

  const subType = isSteelBraided
    ? "Steel Wire Braid (SY) Armoured"
    : isCopperScreened
    ? "Tinned Copper Braid (CY) EMC Screened"
    : isColorCoded
    ? "VDE Color-Coded Cores (100 I)"
    : "PVC Number-Coded Control Cable";

  const colorDesc = isColorCoded
    ? `Silver-Grey (VDE Color-Coded Cores${item.pe === "G" ? " + GN/YE Earth" : ""})`
    : isSteelBraided
    ? `Transparent Sheath (Steel Armoured / Black Numbered${item.pe === "G" ? " + Earth" : ""})`
    : isCopperScreened
    ? `Transparent Sheath (Copper Screened / Black Numbered${item.pe === "G" ? " + Earth" : ""})`
    : `Silver-Grey RAL 7001 (Black Numbered${item.pe === "G" ? " + GN/YE Earth" : ""})`;

  return {
    id: `lapp-olflex-${item.partNo || idx}`,
    category: "cables",
    brand: "LAPP KABEL",
    partNo: `LAPP-${item.partNo}`,
    name: item.name,
    cores: item.core,
    size: item.size,
    pe: item.pe,
    outerDia: item.outerDia,
    color: colorDesc,
    specs: [
      `${item.core} Cores x ${item.size} sq mm (${item.pe === "G" ? "with Earth" : "without Earth"})`,
      subType,
      item.voltage || "300/500 V",
      item.standard || "VDE Reg. No. 7030",
    ],
    voltage: item.voltage || "300/500 V",
    tempRange: item.tempRange || "-40°C to +80°C fixed",
    conductor: `Bare copper wire class 5 (Size ${item.size} mm²)`,
    price: Math.round(item.price || 45),
    unit: "meter",
    stock: "In Stock (Bangalore Hub)",
    icon: "cable",
    application: isSteelBraided
      ? "Mechanical stress protection, production lines, pumps"
      : isCopperScreened
      ? "EMC critical environments, variable frequency drives (VFD)"
      : "Machine tools, automation wiring, control panels",
    image,
  };
});

